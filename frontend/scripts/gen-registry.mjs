// Generates src/server/registry.generated.ts from src/server/modules/<name>/{router,handlers}.ts.
// Module order matters (route matching is first-match, like FastAPI include_router order).
import { existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "server");

const MODULES = [
  "auth", "properties", "parcels", "contacts", "ownership", "territories", "buybox", "pipeline", "outreach",
  "compliance", "tasks", "imports", "search", "dashboard",
  // Release 2 — Intelligence
  "signals", "scoring", "reactivation", "comps", "underwriting", "documents",
  // Release 3 — Transaction
  "offers", "contracts", "closing",
  // Release 4 — Ownership
  "assets", "leases", "receivables", "debt", "dispositions",
  // Release 5 — Operations & Brokerage
  "maintenance", "operations", "investors", "brokerage", "dealroom", "commissions",
  // Release 6 — Leverage / platform
  "map", "reports", "platform",
];

const routers = MODULES.filter((m) => existsSync(join(root, "modules", m, "router.ts")));
const handlers = MODULES.filter((m) => existsSync(join(root, "modules", m, "handlers.ts")));

const out = [
  "// GENERATED by scripts/gen-registry.mjs — do not edit. Run `npm run gen:registry` after adding a module.",
  'import { Router } from "./core/router";',
  ...handlers.map((m) => `import "./modules/${m}/handlers";`),
  ...routers.map((m, i) => `import { router as r${i} } from "./modules/${m}/router";`),
  "",
  "export const apiRouter = new Router();",
  ...routers.map((_m, i) => `apiRouter.use(r${i});`),
  "",
].join("\n");

writeFileSync(join(root, "registry.generated.ts"), out);
console.log(`registry: ${routers.length} routers, ${handlers.length} handler modules`);
const missing = MODULES.filter((m) => !routers.includes(m));
if (missing.length) console.log(`  (no router.ts yet: ${missing.join(", ")})`);
